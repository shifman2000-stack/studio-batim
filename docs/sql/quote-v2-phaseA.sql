-- 5. תבנית ברירת המחדל
--
-- מבנה ה-content: schema + drawingVariant + sections. אין clients,
-- אין vars, אין clientResponse — אלה נולדים בזמן יצירת ההצעה.
--
-- שבעה סעיפים, כל טיפוס פעם אחת:
--   opening ◆ · scope ■ · fee ◆■ · stages ◆■ · extras ◆■ · terms ◆■ · signing ◆■
-- סדר הפרקים בכל פן נקבע בקוד המרנדר ולא לפי סדר המערך כאן.
--
-- תחביר הטקסט, שלושה מנגנונים נפרדים (פרקים A.6 ו-A.7 במסמך התכנון):
--   [[קטע]]        — נמחק כולו אם משתנה כלשהו שבתוכו ריק
--   {{משתנה}}      — מוחלף בערך מהפנייה
--   {יחיד|רבים}    — נבחר לפי מספר הלקוחות
-- סדר הפתרון: קודם קטעים מותנים, אחר כך משתנים, ולבסוף חלופות.
-- הסדר קריטי: אם המשתנים היו נפתרים ראשונים, לא היה נשאר מידע על
-- אילו מהם היו ריקים, והקטע המותנה לא היה יודע אם למחוק את עצמו.
--
-- ⚠️ שטחי הבית והמגרש הם שדות **רשות**. בלעדיהם המשפט חייב להישאר
--    קריא, ולכן כל אזכור שטח עטוף ב-[[…]]. ארבעת המצבים:
--      שניהם:    "בית מגורים של כ-200 מ״ר בכפר ורדים, עם פיתוח מגרש של כ-490 מ״ר."
