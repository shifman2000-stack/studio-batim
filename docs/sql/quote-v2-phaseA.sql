SELECT
  s->>'type',
  CASE s->>'type'
    WHEN 'opening' THEN 'פתיחה — ברירת מחדל'
    WHEN 'scope'   THEN 'תכולת השירות — ברירת מחדל'
    WHEN 'fee'     THEN 'שכר טרחה — ברירת מחדל'
    WHEN 'signing' THEN 'אישור וחתימה — ברירת מחדל'
  END,
