import './Money.css'
import { formatMoney } from '../../lib/quoteV2/payments'

/* ═══════════════════════════════════════════════════════════════════════
   Money — סכום בשקלים, בשני הפנים

   כלל אחד: **השקל תמיד משמאל למספר.** זה הסדר הנכון בעברית, והוא
   מה שעינב והלקוח מצפים לראות.

   למה זה דורש רכיב ולא מחרוזת: `direction: ltr` על התא (שנדרש כדי
   שהמספר והפסיקים ייראו נכון) מעביר את השקל לימין המספר. הפתרון
   הוא בידוד דו-שכבתי —

     .q-money      · RTL מבודד  → השקל נופל שמאלה מהמספר
       <bdi>       · LTR מבודד  → "120,000" נשאר 120,000 ולא מתהפך
       <span>₪</span>

   bdi ולא span כי הוא מבודד bidi מעצם הגדרתו, כך שגם אם הסכום יגיע
   פעם כמחרוזת עם תווים אחרים הוא לא ידלוף על הסביבה.

   כל מקום שמציג ₪ בשני הפנים עובר דרך כאן, ולכן אי אפשר שיהיה
   הבדל בין החוויה למסמך.
   ═══════════════════════════════════════════════════════════════════════ */
export default function Money({ value, className }) {
  return (
    <span className={'q-money' + (className ? ' ' + className : '')} dir="rtl">
      <bdi className="q-money-num">{formatMoney(value)}</bdi>
      <span className="q-money-sign">&nbsp;₪</span>
    </span>
  )
}
