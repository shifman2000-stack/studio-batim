/**
 * מחזיר מערך סכומים, אחד לכל שלב.
 *
 * כלל העיגול (A.3): floor לכל שלב, וההפרש שנוצר מהעיגול מתווסף
 * **לשלב האחרון**. בלי זה, 100,000 ב-7 שלבים של 14.28% ייתן סכום
 * טבלה שקטן מהסכום הכולל, ומישהו יגלה את זה מול לקוח.
 *
 * ההשלמה קורית רק כשהאחוזים מסתכמים ל-100 בדיוק. סכום אחר הוא
 * שגיאת ולידציה (C.3), ושם אסור ל"תקן" אותה בשקט על גב השלב האחרון.
 */
export function computePayments(fee, pcts = []) {
  const total = Number(fee) || 0
  const list = pcts.map(p => Number(p) || 0)
  const amounts = list.map(p => Math.floor((total * p) / 100))

  const pctSum = list.reduce((a, b) => a + b, 0)
  const paid = amounts.reduce((a, b) => a + b, 0)
  if (amounts.length > 0 && pctSum === 100) {
    amounts[amounts.length - 1] += total - paid
  }
  return amounts
}

/** 24000 → "24,000". ספרות לטיניות עם פסיקים, כמו בהצעה המקורית. */
export function formatMoney(n) {
  return (Number(n) || 0).toLocaleString('en-US')
}
